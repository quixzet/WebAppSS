"""
Конфигурация базы данных SQLite

Содержит все параметры для настройки производительности и надёжности БД.
"""

# ========================================
# Основные параметры соединения
# ========================================

# Таймаут ожидания блокировки БД (секунды)
# Увеличен с дефолтных 5 до 30 секунд для обработки длительных транзакций
DATABASE_TIMEOUT = 30

# Путь к файлу базы данных
DATABASE_PATH = "schedule.db"

# ========================================
# Параметры WAL (Write-Ahead Logging)
# ========================================

# Включить WAL-режим для одновременного чтения и записи
WAL_MODE = True

# Режим синхронизации (NORMAL для баланса скорости и надёжности)
# FULL - максимальная надёжность, но медленнее
# NORMAL - хороший баланс (рекомендуется для WAL)
# OFF - максимальная скорость, но риск потери данных при сбое
SYNC_MODE = "NORMAL"

# Размер кэша страниц (отрицательное значение = килобайты)
# -10000 = 10 MB кэша в памяти
CACHE_SIZE = -10000

# Размер memory-mapped I/O (байты)
# 0 = отключено, рекомендуется для больших транзакций
MMAP_SIZE = 268435456  # 256 MB

# ========================================
# Параметры повторных попыток (retry)
# ========================================

# Максимальное количество попыток при ошибке блокировки
MAX_RETRY_ATTEMPTS = 5

# Базовая задержка между попытками (секунды)
# Используется экспоненциальная задержка: base_delay * (2 ^ attempt)
RETRY_BASE_DELAY = 0.5

# Максимальная задержка между попытками (секунды)
RETRY_MAX_DELAY = 8.0

# ========================================
# Параметры пакетной обработки
# ========================================

# Размер батча для массовых вставок
# Если данных больше BATCH_SIZE, они разбиваются на части
BATCH_SIZE = 1000

# ========================================
# Параметры логирования
# ========================================

# Логировать время выполнения каждой операции
LOG_QUERY_TIMING = True

# Порог для предупреждения о медленных запросах (секунды)
SLOW_QUERY_THRESHOLD = 1.0

# ========================================
# Параметры индексов
# ========================================

